"""Live customer lookup against the EasyWeek workspace (preparation stage).

Why this exists next to :mod:`customers`
----------------------------------------
:mod:`customers` resolves a customer from an operator's file export, because when
PR-11.1 was written no customer endpoint was confirmed. Three are confirmed now:

* ``GET  /api/public/v2/customers``                — filtered list
* ``GET  /api/public/v2/customers/{customer_uuid}`` — one card
* ``POST /api/public/v2/customers``                — create

That does not retire the export. The export stays the artefact the *apply* path
reads, so a bulk run is not one lookup per booking against a live API. What this
module changes is where the export comes from: the preparation stage builds it
from the live workspace instead of from a spreadsheet an operator regenerated by
hand, which is where most of the several hours went.

What "not found" is allowed to mean
-----------------------------------
Only one thing: the workspace was read completely and holds no card with this
number. Every other unhappy ending is :data:`LOOKUP_UNDETERMINED` — an auth
failure, a timeout, a malformed page, a page count that does not add up, a
response whose rows do not actually carry the number that was asked for. The
distinction is the whole point of the module: "absent" is the one outcome that
authorises a ``POST``, and a customer created because the API was briefly
unreachable is a duplicate card sitting on top of somebody's visit history.

Customers are WORKSPACE-scoped
------------------------------
The customer object carries no location field, and the same person is reachable
from Durlach, Karlsruhe and Rastatt alike. Nothing here filters by branch. A
lookup that came back empty has said something about the workspace, not about a
branch — and a lookup restricted to one branch would say nothing at all.

PII in the URL
--------------
``phone`` is a query parameter, so the number reaches the one place a log line is
written without anybody deciding to write it. :func:`silence_http_request_logs`
closes that off before the first request, and :class:`PhoneQueryLogFilter` scrubs
the parameter even if something re-enables the logger later. Our own log lines
carry :func:`phone_fingerprint` — enough to correlate two lines, not enough to
call anyone.
"""

from __future__ import annotations

import hashlib
import logging
import re
from dataclasses import dataclass
from typing import Any, Final, Protocol

from altegio_bot.easyweek_migration.customers import (
    CustomerCard,
    normalized_international_phone,
)
from altegio_bot.easyweek_migration.manifest import canonical_uuid
from altegio_bot.easyweek_migration.write_client import (
    EasyWeekAuthError,
    EasyWeekError,
    EasyWeekNotFoundError,
)

logger = logging.getLogger(__name__)

# Outcomes. Exactly one per lookup, and only ABSENT authorises a creation.
LOOKUP_FOUND: Final = "customer_found"
LOOKUP_ABSENT: Final = "customer_absent"
LOOKUP_AMBIGUOUS: Final = "customer_ambiguous"
LOOKUP_PHONE_UNUSABLE: Final = "customer_phone_unusable"
LOOKUP_FIRST_NAME_MISSING: Final = "customer_first_name_missing"
LOOKUP_UNDETERMINED: Final = "customer_lookup_undetermined"

# Why a lookup is undetermined. Stable codes, safe to log and to report.
DETAIL_ACCESS_DENIED: Final = "lookup_access_denied"
DETAIL_TRANSPORT: Final = "lookup_transport_error"
DETAIL_MALFORMED: Final = "lookup_response_malformed"
DETAIL_PAGINATION_INCOMPLETE: Final = "lookup_pagination_incomplete"
DETAIL_PAGINATION_UNBOUNDED: Final = "lookup_pagination_unbounded"
# The server returned rows that do not carry the number we filtered on. Either
# the filter is not the exact match the documentation states, or we are reading
# somebody else's page. Both mean the answer proves nothing.
DETAIL_FILTER_UNVERIFIED: Final = "lookup_filter_unverified"

# A single phone cannot legitimately span this many pages of 100. Reaching it
# means the filter is not filtering, and walking further would only spend the
# rate budget on it.
_MAX_PAGES: Final = 20

_PHONE_QUERY_RE: Final = re.compile(r"((?:phone|email)=)[^&\s\"']+", re.IGNORECASE)


class SupportsCustomerReads(Protocol):
    """The slice of the migration write client this module reads through."""

    async def list_customers(self, *, params: dict[str, Any]) -> dict[str, Any]: ...

    async def get_customer(self, customer_uuid: str) -> dict[str, Any]: ...


# ---------------------------------------------------------------------------
# Keeping phone numbers out of the logs
# ---------------------------------------------------------------------------


class PhoneQueryLogFilter(logging.Filter):
    """Scrub ``phone=`` / ``email=`` out of any record that carries a URL.

    Belt and braces next to :func:`silence_http_request_logs`: that lifts the
    level, this survives somebody lowering it again — a ``-v`` flag, a debug
    session, a library that configures logging on import.
    """

    def filter(self, record: logging.LogRecord) -> bool:
        try:
            message = record.getMessage()
        except Exception:  # pragma: no cover - a broken record must not block the run
            return True
        if "phone=" not in message and "email=" not in message:
            return True
        record.msg = _PHONE_QUERY_RE.sub(r"\1<redacted>", message)
        record.args = ()
        return True


def silence_http_request_logs() -> None:
    """Raise the HTTP loggers to WARNING and attach the scrubbing filter.

    ``httpx`` logs one INFO line per request containing the full URL, and this
    stage's URLs contain ``?phone=%2B49...``. The stage's own progress lines are
    written by us, at our own level; nothing is lost by taking the request lines
    away, and a phone number in a container log is not something that can be
    taken back.
    """
    scrubber = PhoneQueryLogFilter()
    for name in ("httpx", "httpcore", "httpx._client"):
        target = logging.getLogger(name)
        if target.level < logging.WARNING:
            target.setLevel(logging.WARNING)
        if not any(isinstance(existing, PhoneQueryLogFilter) for existing in target.filters):
            target.addFilter(scrubber)


def phone_fingerprint(phone: str) -> str:
    """A stable, non-reversible tag for one number, for logs and reports.

    Two lines about the same customer can be tied together; no line can be tied
    to a person. Deliberately not a prefix/suffix mask: a German mobile masked to
    ``+49...4321`` is still identifying inside one salon's customer base.
    """
    return hashlib.sha256(phone.encode("utf-8")).hexdigest()[:12]


