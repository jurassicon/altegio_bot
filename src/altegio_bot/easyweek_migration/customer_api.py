# The lookup
# ---------------------------------------------------------------------------


async def lookup_customer_by_phone(client: SupportsCustomerReads, raw_phone: object) -> CustomerLookup:
    """Resolve one number against the whole workspace, or say why it could not.

    Never narrowed to a branch, never widened to a name: a name match is not
    evidence of identity, and quietly matching on e-mail instead would answer a
    different question than the one the caller asked.
    """
    phone = normalized_international_phone(raw_phone)
    if phone is None:
        return CustomerLookup(phone=None, outcome=LOOKUP_PHONE_UNUSABLE)

    cards: dict[str, CustomerCard] = {}
    rows_seen = 0
    try:
        page = 1
        while True:
            if page > _MAX_PAGES:
                raise CustomerLookupUndetermined(DETAIL_PAGINATION_UNBOUNDED)
            payload = await client.list_customers(params={"phone": phone, "page": page})
            last_page, total = _read_pagination(payload.get("meta"), page=page)
            for row in _rows(payload):
                rows_seen += 1
                card = read_customer_card(row, expected_phone=phone)
                # The same uuid listed twice is one customer, as in `customers`.
                cards.setdefault(card.uuid, card)
            if page >= last_page:
                if rows_seen < total:
                    # The server counted rows it did not hand over. That is an
                    # unfinished read, and an unfinished read is not an absence —
                    # the row we never saw may be the customer.
                    raise CustomerLookupUndetermined(DETAIL_PAGINATION_INCOMPLETE)
                break
            page += 1
    except CustomerLookupUndetermined as undetermined:
        return CustomerLookup(phone=phone, outcome=LOOKUP_UNDETERMINED, detail=undetermined.detail)
    except EasyWeekAuthError:
        return CustomerLookup(phone=phone, outcome=LOOKUP_UNDETERMINED, detail=DETAIL_ACCESS_DENIED)
    except EasyWeekError:
        # Every remaining client failure — timeout, 5xx, protocol, exhausted
        # retries. None of them has read the workspace.
        return CustomerLookup(phone=phone, outcome=LOOKUP_UNDETERMINED, detail=DETAIL_TRANSPORT)

    if not cards:
        return CustomerLookup(phone=phone, outcome=LOOKUP_ABSENT)
    if len(cards) > 1:
        # Two cards on one number: a couple, a family phone, a duplicated import.
        # Not something to auto-merge and not something to pick a winner from.
        return CustomerLookup(phone=phone, outcome=LOOKUP_AMBIGUOUS, match_count=len(cards))

    card = next(iter(cards.values()))
    if not card.addressable:
        return CustomerLookup(
            phone=phone,
            outcome=LOOKUP_FIRST_NAME_MISSING,
            uuid=card.uuid,
            card=card,
            match_count=1,
        )
    return CustomerLookup(phone=phone, outcome=LOOKUP_FOUND, uuid=card.uuid, card=card, match_count=1)


async def verify_customer(client: SupportsCustomerReads, customer_uuid: str, *, expected_phone: str) -> CustomerCard:
    """``GET /customers/{uuid}`` after a creation, and check what came back.

    The ``POST`` response is the server describing its own intent; this is the
    workspace. Raises :class:`CustomerLookupUndetermined` when the card cannot be
    read or does not carry the expected number, so a caller cannot record a
    creation it has not seen.
    """
    canonical = canonical_uuid(customer_uuid)
    if canonical is None:
        raise CustomerLookupUndetermined(DETAIL_MALFORMED)
    try:
        payload = await client.get_customer(canonical)
    except EasyWeekNotFoundError:
        raise CustomerLookupUndetermined(DETAIL_MALFORMED) from None
    except EasyWeekAuthError:
        raise CustomerLookupUndetermined(DETAIL_ACCESS_DENIED) from None
    except EasyWeekError:
        raise CustomerLookupUndetermined(DETAIL_TRANSPORT) from None

    body = payload.get("data") if isinstance(payload.get("data"), dict) else payload
    card = read_customer_card(body, expected_phone=expected_phone)
    if card.uuid != canonical:
        raise CustomerLookupUndetermined(DETAIL_FILTER_UNVERIFIED)
    return card
