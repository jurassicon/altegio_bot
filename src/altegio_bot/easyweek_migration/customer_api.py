# Reading one response
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class CustomerLookup:
    """One resolution attempt against the live workspace."""

    phone: str | None
    outcome: str
    uuid: str | None = None
    card: CustomerCard | None = None
    match_count: int = 0
    detail: str | None = None

    @property
    def found(self) -> bool:
        return self.outcome == LOOKUP_FOUND

    @property
    def creatable(self) -> bool:
        """Only a proven absence authorises a ``POST``."""
        return self.outcome == LOOKUP_ABSENT

    def as_safe_dict(self) -> dict[str, Any]:
        """Log/report shape. No number, no name — a fingerprint and a code."""
        return {
            "phone": phone_fingerprint(self.phone) if self.phone else None,
            "outcome": self.outcome,
            "customer_uuid": self.uuid,
            "match_count": self.match_count,
            "detail": self.detail,
        }


class CustomerLookupUndetermined(Exception):
    """Raised internally to carry a stable detail code out of a page read."""

    def __init__(self, detail: str) -> None:
        super().__init__(detail)
        self.detail = detail


def _read_pagination(meta: object, *, page: int) -> tuple[int, int]:
    """``(last_page, total)`` from a response envelope, or refuse.

    Deliberately not reusing the catalogue reader: identical strictness, but the
    codes an operator sees have to say which read was incomplete. A missing or
    non-integer field is malformed rather than "assume one page" — assuming one
    page is exactly how a second page holding the real customer gets skipped and
    the answer becomes a wrong "absent".
    """
    if not isinstance(meta, dict):
        raise CustomerLookupUndetermined(DETAIL_MALFORMED)

    def _int(key: str) -> int:
        value = meta.get(key)
        if isinstance(value, bool) or not isinstance(value, int):
            raise CustomerLookupUndetermined(DETAIL_MALFORMED)
        return value

    current_page = _int("current_page")
    last_page = _int("last_page")
    total = _int("total")
    if current_page != page:
        # The server answered a different page than the one asked for. Merging
        # it into the accumulator would double-count or skip.
        raise CustomerLookupUndetermined(DETAIL_PAGINATION_INCOMPLETE)
    if last_page < 1 or total < 0:
        raise CustomerLookupUndetermined(DETAIL_MALFORMED)
    return last_page, total


def read_customer_card(payload: object, *, expected_phone: str | None = None) -> CustomerCard:
    """One customer object → a card, verifying rather than trusting.

    ``expected_phone`` is checked when given: a 200 is not proof that the row
    belongs to the number we asked about.
    """
    if not isinstance(payload, dict):
        raise CustomerLookupUndetermined(DETAIL_MALFORMED)

    customer_uuid = canonical_uuid(payload.get("uuid") or payload.get("id"))
    if customer_uuid is None:
        raise CustomerLookupUndetermined(DETAIL_MALFORMED)

    phone = normalized_international_phone(payload.get("phone"))
    if phone is None:
        # A card we cannot read the number of cannot be proven to be this
        # customer's, and cannot be used to prove one absent either.
        raise CustomerLookupUndetermined(DETAIL_FILTER_UNVERIFIED)
    if expected_phone is not None and phone != expected_phone:
        raise CustomerLookupUndetermined(DETAIL_FILTER_UNVERIFIED)

    raw_first = payload.get("first_name")
    first_name = " ".join(raw_first.split()) if isinstance(raw_first, str) else None
    return CustomerCard(uuid=customer_uuid, phone=phone, first_name=first_name or None)


def _rows(payload: dict[str, Any]) -> list[Any]:
    data = payload.get("data")
    if not isinstance(data, list):
        raise CustomerLookupUndetermined(DETAIL_MALFORMED)
    return data


